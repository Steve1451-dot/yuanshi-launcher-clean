inline bool chinese=true;
inline void LoadLanguage(const std::string& path) {
    chinese=true;
    for(const auto& file:{path,path+".bak"}) {
        std::ifstream in(file,std::ios::binary); char value[3]{};
        if(in.read(value,2) && (std::string_view(value,2)=="zh" || std::string_view(value,2)=="en")) {
            chinese=value[0]=='z';return;
        }
    }
}
inline bool SaveLanguage(const std::string& path) {
    std::ofstream out(path+".tmp",std::ios::binary|std::ios::trunc);
    if(!out) return false;
    out<<(chinese ? "zh" : "en");out.flush();const bool ok=out.good();out.close();
    if(!ok || out.fail()) return false;
    return opennow::storage::ReplaceWithTemporaryFile(path+".tmp",path);
}
